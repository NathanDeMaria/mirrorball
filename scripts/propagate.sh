#!/usr/bin/env bash
# Open a `copier update` PR in every repo listed in repos.txt.
#
#   scripts/propagate.sh [REF]       REF defaults to the newest tag
#   DRY_RUN=1 scripts/propagate.sh   update and show the diff, push nothing
#
# Each repo is cloned fresh into a scratch directory, so nothing here touches a
# checkout you're working in. Conflicts are left inline (<<<<<<< markers) and
# the PR opens as a draft that says so; the repo's `ci` check fails on them
# until they're resolved, which is the point. Needs copier, uv and an
# authenticated gh.
set -euo pipefail

here="$(cd "$(dirname "$0")/.." && pwd)"
ref="${1:-$(git -C "$here" describe --tags --abbrev=0)}"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

grep -vE '^\s*(#|$)' "$here/repos.txt" | while read -r repo subdir; do
    name="${repo#*/}${subdir:+-${subdir//\//-}}"
    dest="$work/$name"
    branch="template/$ref${subdir:+-${subdir//\//-}}"
    echo "== $repo ${subdir:-}"

    gh repo clone "$repo" "$dest" -- --quiet
    cd "$dest"
    git checkout --quiet -b "$branch"

    project="${subdir:-.}"
    copier update --defaults --quiet --conflict inline --vcs-ref "$ref" "$project"
    # pyproject.toml may have moved; keep the lock in step with it
    (cd "$project" && uv lock --quiet)

    if git diff --quiet && [ -z "$(git ls-files --others --exclude-standard)" ]; then
        echo "   already at $ref"
        cd "$here"
        continue
    fi

    conflicts="$(git grep -lE '^<{7}( |$)' || true)"
    if [ -n "${DRY_RUN:-}" ]; then
        git status --short
        [ -n "$conflicts" ] && echo "   conflicts in: $conflicts"
        cd "$here"
        continue
    fi

    git add -A
    git commit --quiet -m "Update to mirrorball $ref"
    git push --quiet -u origin "$branch"

    body="Generated by \`mirrorball/scripts/propagate.sh\`: \`copier update\` to [mirrorball $ref](https://github.com/NathanDeMaria/mirrorball/releases/tag/$ref)."
    draft=()
    if [ -n "$conflicts" ]; then
        body+=$'\n\nConflicts to resolve by hand (inline `<<<<<<<` markers):\n'
        body+="$(printf -- '- `%s`\n' $conflicts)"
        draft=(--draft)
    fi
    gh pr create "${draft[@]}" --title "Update to mirrorball $ref${subdir:+ ($subdir)}" --body "$body"
    cd "$here"
done
